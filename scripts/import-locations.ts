import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import type { Location } from "../shared/types";
import { identityKey, validateLocation } from "../worker/validation";
import { locationStatements } from "../worker/location-sql";

export function validateImport(input: unknown): Location[] {
  if (!Array.isArray(input) || input.length === 0 || input.length > 5000)
    throw new Error(
      "Import requires an array containing 1 to 5,000 locations. Split larger imports into reviewed batches.",
    );
  const seenIds = new Set<string>(),
    seenSlugs = new Set<string>(),
    seenIdentity = new Set<string>();
  const locations: Location[] = [];
  const errors: string[] = [];
  for (const [index, row] of input.entries()) {
    try {
      const location = validateLocation(row);
      const identity = identityKey(location);
      if (
        seenIds.has(location.id) ||
        seenSlugs.has(location.slug) ||
        seenIdentity.has(identity)
      )
        throw new Error(
          `Duplicate id, slug, or name/city/state/country identity: ${location.name}`,
        );
      seenIds.add(location.id);
      seenSlugs.add(location.slug);
      seenIdentity.add(identity);
      locations.push(location);
    } catch (error) {
      errors.push(
        `Row ${index + 1}: ${error instanceof Error ? error.message : error}`,
      );
    }
  }
  if (errors.length) throw new Error(errors.join("\n"));
  return locations;
}

export function toSql(locations: Location[]): string {
  const quote = (value: string | number | null) =>
    value === null
      ? "NULL"
      : typeof value === "number"
        ? String(value)
        : `'${value.replace(/'/g, "''")}'`;
  return `-- Generated by PHASM's validated import pipeline. Review publication status before applying.\n-- Existing duplicate ids, slugs, or normalized identities are rejected by database constraints.\n${locations
    .flatMap((location) =>
      locationStatements(location).map((statement) => {
        let index = 0;
        return `${statement.sql.replace(/\?/g, () => quote(statement.params[index++]))};`;
      }),
    )
    .join("\n")}\n`;
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  try {
    const args = process.argv.slice(2);
    let filename = "content/locations.json";
    let hasFilename = false;
    let output: string | undefined;
    for (let index = 0; index < args.length; index++) {
      const argument = args[index];
      if (argument === "--write-sql") {
        output = args[++index];
        if (!output || output.startsWith("--"))
          throw new Error("--write-sql requires an output file.");
      } else if (argument.startsWith("--"))
        throw new Error(`Unknown option: ${argument}`);
      else if (hasFilename)
        throw new Error("Provide only one input JSON file.");
      else {
        filename = argument;
        hasFilename = true;
      }
    }
    const locations = validateImport(
      JSON.parse(readFileSync(resolve(filename), "utf8")),
    );
    if (output) {
      writeFileSync(resolve(output), toSql(locations));
      console.log(
        `Validated ${locations.length} locations. Reviewable SQL written to ${output}. No database was changed.`,
      );
    } else
      console.log(
        `Validated ${locations.length} locations: ${locations.filter((location) => location.status === "published").length} published, ${locations.filter((location) => location.status !== "published").length} unpublished. No duplicate ids, slugs, or normalized identities.`,
      );
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}
